"""
================================================================================
BOILERPLATE: Interactive Codebase Access & Permission-Gated Patcher
Pattern: Human-in-the-Loop (HITL) Autonomous File Editor
Use Case: Allows Equis agent to read workspace files and proposal diffs,
requiring explicit user permission (approval token) before modifying codebase.
================================================================================
"""
import os
import difflib
from pathlib import Path
from typing import Optional, Dict, Any
from pydantic import BaseModel, Field

# Allowed file extensions for game engine projects
SAFE_EXTENSIONS = {".cpp", ".h", ".hpp", ".inl", ".hlsl", ".glsl", ".usf", ".ush", ".ini", ".cs", ".py", ".json", ".yaml", ".txt"}


class CodePatchProposal(BaseModel):
    """Proposal generated by agent for code modification."""
    file_path: str
    original_snippet: str
    replacement_snippet: str
    diff: str
    explanation: str
    status: str = "pending_approval"  # pending_approval, approved, rejected, applied


def preview_file(workspace_root: str, relative_path: str, start_line: int = 1, max_lines: int = 100) -> Dict[str, Any]:
    """Safely inspect a file within the workspace boundary."""
    root = Path(workspace_root).resolve()
    target = (root / relative_path).resolve()

    # Sandboxing check: prevent path traversal outside workspace
    if not str(target).startswith(str(root)):
        return {"error": "Path traversal rejected: Access outside workspace is prohibited."}

    if not target.exists():
        return {"error": f"File not found: {relative_path}"}

    if target.suffix not in SAFE_EXTENSIONS:
        return {"error": f"Access denied: file type '{target.suffix}' is not permitted."}

    try:
        with open(target, "r", encoding="utf-8", errors="replace") as f:
            lines = f.readlines()
        
        subset = lines[start_line - 1: start_line - 1 + max_lines]
        return {
            "file_path": relative_path,
            "total_lines": len(lines),
            "content": "".join(subset),
            "start_line": start_line
        }
    except Exception as e:
        return {"error": f"Failed to read file: {e}"}


def create_patch_proposal(workspace_root: str, relative_path: str, original: str, replacement: str, reason: str) -> Dict[str, Any]:
    """Generate a unified diff patch proposal for user review."""
    root = Path(workspace_root).resolve()
    target = (root / relative_path).resolve()

    if not str(target).startswith(str(root)):
        return {"error": "Path traversal rejected."}

    if not target.exists():
        return {"error": f"File does not exist: {relative_path}"}

    try:
        with open(target, "r", encoding="utf-8") as f:
            file_content = f.read()

        if original not in file_content:
            return {"error": "Target original snippet not found in file."}

        new_content = file_content.replace(original, replacement, 1)
        diff = difflib.unified_diff(
            file_content.splitlines(keepends=True),
            new_content.splitlines(keepends=True),
            fromfile=f"a/{relative_path}",
            tofile=f"b/{relative_path}"
        )
        diff_text = "".join(diff)

        return {
            "file_path": relative_path,
            "diff": diff_text,
            "explanation": reason,
            "requires_user_approval": True,
            "status": "pending_approval"
        }
    except Exception as e:
        return {"error": str(e)}


def apply_patch_with_approval(workspace_root: str, relative_path: str, original: str, replacement: str, approved: bool) -> Dict[str, Any]:
    """Apply the patch ONLY if the user has approved it."""
    if not approved:
        return {"success": False, "message": "Permission denied: User declined to apply patch."}

    root = Path(workspace_root).resolve()
    target = (root / relative_path).resolve()

    if not str(target).startswith(str(root)):
        return {"success": False, "message": "Security boundary error."}

    try:
        with open(target, "r", encoding="utf-8") as f:
            content = f.read()

        if original not in content:
            return {"success": False, "message": "Original snippet is no longer present."}

        updated = content.replace(original, replacement, 1)
        with open(target, "w", encoding="utf-8") as f:
            f.write(updated)

        return {
            "success": True,
            "message": f"Successfully patched {relative_path}",
            "file_path": relative_path
        }
    except Exception as e:
        return {"success": False, "message": f"Write failed: {e}"}
